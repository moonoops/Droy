export function translateBackendText(text, locale) {
  if (typeof text !== 'string' || normalizeMobileLocale(locale) === 'zh') return text;
  if (Object.hasOwn(backendMessages, text)) return backendMessages[text];
  let match = /^正在生成(.+)（(\d+)\/(\d+)）$/u.exec(text);
  if (match && Object.hasOwn(backendMessages, match[1])) return `Generating ${backendMessages[match[1]]} (${match[2]}/${match[3]})`;
  match = /^(.+)的第(\d+)行(存在空帧或越界，请重做这一组|动作没有变化，请重做这一组)$/u.exec(text);
  if (match && Object.hasOwn(backendMessages, match[1])) return `${backendMessages[match[1]]}, row ${match[2]}: ${match[3].startsWith('存在') ? 'empty or out-of-bounds frames' : 'no animation variation'}. Regenerate this group.`;
  match = /^(外观描述|性格描述|形象方案名称|动作倾向)(无效|请填写(不超过|1–)(\d+)个字符)$/u.exec(text);
  if (match) return match[2] === '无效' ? `Invalid ${backendMessages[match[1]].toLowerCase()}.`
    : `${backendMessages[match[1]]} must contain ${match[3] === '不超过' ? 'at most ' : '1–'}${match[4]} characters.`;
  // A combined availability message contains only these two owned sentences.
  const configuration = ['请先配置用于理解伙伴性格的文本模型。', '请先在模型设置中选择可用的文本模型，用于理解伙伴性格。'];
  for (const prefix of configuration) if (text.startsWith(`${prefix} `)) {
    const rest = text.slice(prefix.length + 1);
    if (Object.hasOwn(backendMessages, rest)) return `${backendMessages[prefix]} ${backendMessages[rest]}`;
  }
  return text;
}

export function localizePetView(value, locale) {
  if (!value || typeof value !== 'object') return value;
  return { ...value, stage: translateBackendText(value.stage, locale), error: translateBackendText(value.error, locale),
    groups: value.groups?.map(group => ({ ...group, label: translateBackendText(group.label, locale) })) };
}

export function localizePetResponse(value, locale) {
  return { ...value, ...(Object.hasOwn(value, 'configurationMessage') ? { configurationMessage: translateBackendText(value.configurationMessage, locale) } : {}),
    ...(value.pet ? { pet: localizePetView(value.pet, locale) } : {}),
    ...(value.pets ? { pets: value.pets.map(pet => localizePetView(pet, locale)) } : {}) };
}

export function localizeSetupResponse(value, locale) {
  if (!value || typeof value !== 'object') return value;
  return { ...value,
    ...(typeof value.message === 'string' ? { message: translateBackendText(value.message, locale) } : {}),
    ...(typeof value.detail === 'string' ? { detail: translateBackendText(value.detail, locale) } : {}),
    ...(value.modelVerification ? { modelVerification: localizeSetupResponse(value.modelVerification, locale) } : {}),
    ...(value.verification ? { verification: localizeSetupResponse(value.verification, locale) } : {}),
    ...(value.test ? { test: localizeSetupResponse(value.test, locale) } : {}),
    ...(value.state ? { state: localizeSetupResponse(value.state, locale) } : {}) };
}
