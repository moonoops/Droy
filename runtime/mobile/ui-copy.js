const DROY_UI_EN_SOURCES = new Map(Object.entries(DROY_UI_COPY.en).map(([source, english]) => [english, source]));
let droyLocale;
function droyText(source, values) {
  const language = droyLocale?.getSnapshot().active === 'en' ? 'en' : 'zh';
  const stage = typeof source === 'string' && /^正在生成(.+)（(\d+)\/(\d+)）$/.exec(source);
  if (stage) return droyText('正在生成{0}（{1}/{2}）', [droyText(stage[1]), stage[2], stage[3]]);
  const key = DROY_UI_EN_SOURCES.get(source) ?? source;
  const text = DROY_UI_COPY[language][key] ?? source;
  if (!values || typeof text !== 'string') return text;
  return text.replace(/\{(\d+)\}/g, (match, index) => index in values ? String(values[index]) : match);
}
